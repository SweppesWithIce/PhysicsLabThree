def fmt(x, nd=4):
    """Число с запятой, как принято в отчёте."""
    return f"{x:.{nd}f}".replace(".", ",")


def read_freefall(hz):
    with open(os.path.join(DATA, f"freefall_{hz}.csv")) as f:
        rows = [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]
    last = rows[-1]
    max_dev = max(abs(r["err"] - r["err_pred"]) for r in rows)
    return last, max_dev


def read_csv(name):
    with open(os.path.join(DATA, name)) as f:
        return [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]


def max_sigma(rows, n=1000):
    """Наибольшее отклонение доли от теории в единицах стандартной ошибки √(p(1−p)/n)."""
    worst = 0.0
    for r in rows:
        for k, th in (("p_miss", "th_miss"), ("p_pass", "th_pass")):
            p = r[th]
            sd = (p * (1 - p) / n) ** 0.5
            d = abs(r[k] - p)
            if sd > 1e-9:
                worst = max(worst, d / sd)
    return worst


def read_tunnel_positions():
    """Последовательности положений снаряда у стенки из data/tunnel_positions.txt."""
    return read_tunnel_positions_file("tunnel_positions.txt")


def read_tunnel_positions_file(name):
    out = []
    with open(os.path.join(DATA, name)) as f:
        cur = None
        for line in f:
            m = re.match(r"tunnel: hz=(\d+) v=(\d+) L=v\*dt=([\d.]+)(?:.*?fast_hz=(\d+))?", line)
            if m:
                cur = {"hz": int(m[1]), "v": int(m[2]), "L": float(m[3]),
                       "fast_hz": int(m[4]) if m[4] else int(m[1])}
                out.append(cur)
            elif "positions relative" in line and cur is not None:
                cur["xs"] = [float(x) for x in line.split(":")[1].split()]
            elif "outcome:" in line and cur is not None:
                cur["outcome"] = line.split(":", 1)[1].strip().split()[0]
    return out


def read_determinism(name="determinism.txt"):
    runs = []
    with open(os.path.join(DATA, name)) as f:
        block = None
        for line in f:
            m = re.match(r"determinism: bodies=(\d+) steps=(\d+)(?: room=(\d))?(?: mode=(\w+))?", line)
            if m:
                block = {"bodies": int(m[1]), "steps": int(m[2]), "room": m[3] == "1",
                         "mode": m[4] or "discrete", "hashes": [], "frames": None}
                runs.append(block)
            m = re.search(r"hash=([0-9a-f]+)", line)
            if m and block is not None:
                block["hashes"].append(m[1])
            m = re.search(r"\((\d+) frames", line)
            if m and block is not None:
                block["frames"] = int(m[1])
    return runs


