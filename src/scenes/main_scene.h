#pragma once
// Основная сцена для сравнения режимов (часть 2 задания).
//
//   неподвижные тела: пол, две стены и 6 препятствий 60×60 px — в 2 раза
//                     больше обычных тел (их средний размер ≈ 30 px); всего 9;
//   обычные тела:     стек из 10 блоков 50×18 px (верх ниже дорожек снарядов,
//                     чтобы снаряды не задевали его) и 40 тел 18…38 px, которые
//                     падают на препятствия-полки и на пол (группа Normal);
//   быстрые тела:     5 снарядов 8×8 px, летят без гравитации со скоростью v
//                     в три препятствия-мишени; перезапускаются каждые fireEvery с.
//                     Стартовая x каждого снаряда в залпе случайна (0…80 px, свой LCG
//                     с фиксированным seed) — фаза относительно шагов физики меняется,
//                     а последовательность одинакова во всех режимах.
//
// Сцена считает «проскоки»: снаряд за один шаг (тик) оказался по другую
// сторону центра препятствия, перекрываясь с ним по высоте, — т.е. прошёл
// сквозь него. Счёт ведётся по prevPos → pos, поэтому одинаково работает во
// всех режимах (в multi-rate prevPos — начало медленного тика). Каждый выстрел
// даёт не больше одного проскока и только на первом подлёте (до первого отскока).
#include <cstdint>
#include <vector>
#include "core/world.h"

namespace scenes {

struct MainSceneConfig {
    int nNormal = 40;          // обычных тел кроме стека
    int stackBlocks = 10;
    int nFast = 5;
    double projSpeed = 4000;   // px/с
    double fireEvery = 1.5;    // с между залпами
    // Время жизни снаряда после выстрела, с: за 0,5 с снаряд долетает до мишени и
    // отскакивает; потом он убирается за пределы комнаты, чтобы не носиться по
    // сцене (гравитации у снарядов нет) и не сбивать стек — иначе замер
    // устойчивости стека смешивался бы с попаданиями шальных снарядов.
    double projLifetime = 0.5;
    uint64_t seed = 11;
};

class MainScene {
public:
    MainSceneConfig cfg;

    void build(phys::World& w);
    // Вызывать после каждого шага физики (dt — длина этого шага).
    void afterStep(phys::World& w, double dt);
    // Залп: вернуть снаряды на старт с исходной скоростью.
    void fire(phys::World& w);

    int tunnelEvents = 0;      // сколько раз снаряд прошёл сквозь препятствие
    bool firedThisStep = false; // залп был в последнем afterStep (для очистки следа на экране)
    int shots = 0;             // сколько снарядов выпущено
    int stackFirst = -1, stackTop = -1;
    static constexpr double kStackBlockH = 18, kStackX = 150;
    double stackTopY0 = 0;     // начальное положение центра верхнего блока
    std::vector<int> fastIdx, obstacleIdx;

private:
    std::vector<phys::Vec2> fastStart_;
    std::vector<bool> armed_;  // снаряд ещё летит первым подлётом после выстрела
    double sinceShot_ = 0;     // время с последнего залпа
    void park(phys::World& w);
    uint64_t fireRng_ = 0;     // состояние генератора стартовых положений залпов
    double sinceFire_ = 0;
};

} // namespace scenes
